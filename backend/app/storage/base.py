"""Storage abstraction.

Answer-sheet artefacts are large binaries and must not live in PostgreSQL. The
application talks only to this interface; local filesystem is used in
development and any S3-compatible object store in production.
"""

from __future__ import annotations

from typing import Protocol, runtime_checkable


#: Prefixes used to keep artefacts organised and easy to lifecycle-manage.
class KeySpace:
    ORIGINAL = "originals"
    PAGES = "pages"
    THUMBNAILS = "thumbnails"
    PROCESSED = "processed"


def sanitize_key(key: str) -> str:
    """Reject path-traversal and absolute keys.

    Storage keys are generated by the application, but uploads and API input can
    influence filenames, so every key is validated before use.
    """
    if not key or not key.strip():
        raise ValueError("Storage key must not be empty.")
    if "\x00" in key:
        raise ValueError("Storage key must not contain NUL bytes.")

    raw = key.replace("\\", "/")
    if raw.startswith("/"):
        raise ValueError(f"Unsafe storage key rejected: {key!r}")

    normalised = raw.strip("/")
    if not normalised:
        raise ValueError("Storage key must not be empty.")
    for segment in normalised.split("/"):
        if segment in ("", ".", ".."):
            raise ValueError(f"Unsafe storage key rejected: {key!r}")
    return normalised


def build_key(*parts: str) -> str:
    """Compose a safe storage key from path segments."""
    cleaned = [sanitize_key(str(p)) for p in parts if p not in (None, "")]
    return "/".join(cleaned)


@runtime_checkable
class StorageBackend(Protocol):
    name: str

    async def save(self, key: str, data: bytes, *, content_type: str | None = None) -> str:
        """Persist ``data`` under ``key`` and return the stored key."""
        ...

    async def read(self, key: str) -> bytes: ...

    async def delete(self, key: str) -> None: ...

    async def exists(self, key: str) -> bool: ...

    async def health(self) -> dict: ...


class StorageError(Exception):
    """Raised when an artefact cannot be stored or retrieved."""
